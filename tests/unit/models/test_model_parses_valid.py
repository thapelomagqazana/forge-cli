"""Golden-fixture tests: every valid blueprint parses into the typed model.

What this test is *for*
-----------------------
``test_schema_model_parity.py`` proves the schema and the models *agree*
on accept/reject. That is a strong property, but it is not enough on its
own: two broken engines can agree perfectly and both reject a document
that is obviously valid. This file anchors the *positive* half of the
contract with hand-curated examples whose validity is reviewed by a
human, not generated by a property.

Concretely, this test pins:

1. **Every target blueprint parses.** The three blueprints the project
   ships (``python-api``, ``python-automation``, ``typescript-frontend``)
   are the ones a user actually runs ``forge create`` against. If one of
   them cannot be parsed into the model, the tool is broken for its
   primary use case. The other tests all use smaller, synthetic
   fixtures; this is the only one that exercises real, shipped
   blueprints end to end.

2. **Every property-test seed parses.** The seeds in
   ``tests/fixtures/blueprints/property/`` are the ones Hypothesis
   starts from when checking schema↔model parity. If one of them cannot
   be parsed, the parity test's baseline is corrupt and its failures
   become meaningless — but the parity test's own failure message would
   not make that clear. Running them here means a broken seed reports
   its filename directly.

3. **The returned instance is a ``Blueprint``.** Not a ``dict``, not a
   ``BaseModel`` — the concrete generated root type. Downstream code
   (``create.py``, the generation layer, the verification contract) is
   written against this type, so a future refactor that returns a
   subclass or a wrapper would silently break every consumer. Asserting
   the exact type in a dedicated test is the cheapest way to make that
   breakage loud.

4. **The instance is structurally navigable.** Parsing successfully is
   necessary but not sufficient — a model that parses but has ``None``
   where it should have a list, or that loses a field on the way
   through, is a different kind of broken. The tests below assert
   specific, small facts about parsed instances (``.id``, ``.category``
   as an enum, ``.verification`` length, ``.metadata()`` output). These
   are not exhaustive; they are representative. Exhaustive field
   coverage would duplicate the model's own definitions and would go
   stale on every schema change.

What this test is *not* for
---------------------------
* **Negative cases.** Those live in ``test_schema_rejects.py`` and
  ``test_model_error_messages.py``. Adding a negative case here would
  force the file to be re-read every time a contributor wants to know
  "does this parse?" — the answer should always be yes in this file,
  with no exceptions, so a failure is unambiguously a regression.

* **Parity.** That is ``test_schema_model_parity.py``'s job. If a
  valid fixture stops parsing, this file tells you *which fixture*;
  the parity test tells you whether the schema agrees. The two
  failures have different meanings, so they belong to different files.

* **Regeneration drift.** That is ``test_generated_in_sync.py``'s
  job — it checks that the committed models match what the schema
  would generate.

Design notes
------------
* **Loaded via a shared helper.** ``_load_document`` and
  ``_valid_fixture_paths`` are defined once at module level, so
  parameterisation is data-driven: adding a YAML file to either
  directory automatically extends this test without editing it. A
  contributor adding a fixture should *not* have to also remember to
  add a test case — the fixture is the test case.

* **``Path.glob`` results are sorted.** ``Path.glob`` does not
  guarantee order across filesystems; a non-deterministic test run is
  a non-reproducible test run. Sorting the glob output costs nothing
  and makes a failing run identical on every machine.

* **Marker = unit.** These tests read files from disk but do no I/O
  beyond that, spawn no subprocesses, and mutate no state. They are
  unit tests by the project's own definition (see ``pyproject.toml``'s
  ``markers`` list). Marking them ``integration`` would exclude them
  from the fast feedback loop that ``make test`` runs, which is exactly
  where a broken fixture should be caught.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from forge.models import Blueprint, Category
from forge.verification import validate_blueprint_document

# ---------------------------------------------------------------------------
# Fixture paths
# ---------------------------------------------------------------------------
# ``parents[2]`` walks from this file (``tests/unit/models/``) up to the
# repo root. Using ``__file__`` rather than ``Path.cwd()`` makes the
# paths independent of the directory pytest happens to be invoked from,
# which matters for IDE runners and for ``pytest -k`` invocations from
# arbitrary subdirectories.
_REPO_ROOT = Path(__file__).resolve().parents[3]
_VALID_DIR = _REPO_ROOT / "tests" / "fixtures" / "blueprints" / "valid"
_PROPERTY_DIR = _REPO_ROOT / "tests" / "fixtures" / "blueprints" / "property"


def _load_document(path: Path) -> dict[str, object]:
    """Load a YAML fixture and return the parsed mapping.

    ``yaml.safe_load`` is used rather than ``yaml.load`` — the fixtures
    are checked into the repo, but a future contributor copying a
    fixture from an external source should not be able to smuggle a
    ``!!python/object`` constructor into the test suite. ``safe_load``
    is the only correct default for this project (documented in
    ``forge.generation``, which applies the same rule to user-supplied
    blueprints).

    ``dict[str, object]`` is not quite the type of a YAML document —
    it could be a list at the top level — but the schema requires a
    mapping at the root, so any fixture that is not a mapping will fail
    validation with a clear message rather than at the type boundary.
    The annotation tells the reader "we expect a mapping" without
    lying about what ``yaml.safe_load`` returns.
    """
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert isinstance(raw, dict), (
        f"fixture {path.name} did not parse to a mapping; " f"got {type(raw).__name__}"
    )
    return raw


def _valid_fixture_paths() -> list[Path]:
    """Return the sorted list of *target* blueprint fixtures.

    Sorted so a failing parameterisation reports fixtures in a stable
    order. The list is materialised rather than returned as a generator
    because pytest's ``parametrize`` consumes it eagerly and a
    generator would be exhausted after the first collection — a
    subtle, hard-to-diagnose test bug.
    """
    return sorted(_VALID_DIR.glob("*.yaml"))


def _property_fixture_paths() -> list[Path]:
    """Return the sorted list of property-test seed fixtures.

    Separate from ``_valid_fixture_paths`` only by directory. Keeping
    the two helpers distinct means a future refactor that renames the
    ``property`` directory fails with a clear, localised error instead
    of silently returning an empty list (which would make the whole
    parametrised test collect zero cases and pass vacuously — the
    worst possible failure mode for a test suite).
    """
    return sorted(_PROPERTY_DIR.glob("*.yaml"))


# Guard against vacuous parametrisation.
#
# ``pytest.mark.parametrize("path", [])`` collects zero cases and
# *passes*. That is the correct behaviour for the framework and the
# wrong behaviour for this test: a rename or a directory move that
# emptied the glob would silently delete coverage. The assertion below
# runs at import time (before any test), so a missing directory is a
# collection error rather than a green build with a ghost of a test.
assert _VALID_DIR.is_dir(), f"missing fixture directory: {_VALID_DIR}"
assert _PROPERTY_DIR.is_dir(), f"missing fixture directory: {_PROPERTY_DIR}"
assert _valid_fixture_paths(), (
    f"no *.yaml fixtures found in {_VALID_DIR}; "
    "the test would collect zero cases and pass vacuously"
)
assert _property_fixture_paths(), (
    f"no *.yaml fixtures found in {_PROPERTY_DIR}; "
    "the test would collect zero cases and pass vacuously"
)


# ---------------------------------------------------------------------------
# Target blueprints
# ---------------------------------------------------------------------------
@pytest.mark.unit()
@pytest.mark.parametrize(
    "fixture_path",
    _valid_fixture_paths(),
    ids=lambda p: p.stem,
)
def test_target_blueprint_parses_into_blueprint_model(fixture_path: Path) -> None:
    """Every shipped blueprint parses into a ``Blueprint`` instance.

    This is the test that most directly answers the question "does
    ``forge create`` work at all?" If one of these fails, no amount of
    schema or model unit-testing matters — the tool cannot generate a
    project from the blueprint it advertises.

    The test does three things in sequence, each of which is
    load-bearing:

    1. **Parses without raising.** If the funnel raises, the whole
       test fails with the funnel's own structured error, which names
       the exact JSON Pointer that was rejected — the most useful
       possible failure message.

    2. **Returns a ``Blueprint``.** ``isinstance`` rather than
       ``type(...) is Blueprint`` because a future refactor might
       legitimately return a ``Blueprint`` subclass (e.g., a
       ``BlueprintWithOrigin`` that carries the file path). The
       contract is "usable as a Blueprint", not "is exactly this
       class".

    3. **Exposes basic identity.** ``.id`` must equal the raw
       document's ``id``. This is a minimal round-trip check: if the
       model parses but loses or transforms the ID, every downstream
       lookup will be wrong, and the parity test would not catch it
       (parity checks accept/reject, not value preservation).
    """
    document = _load_document(fixture_path)

    # The funnel is the only supported entry point — calling
    # ``Blueprint.model_validate`` directly would bypass the schema
    # check and hide a schema-side regression behind a model-side
    # acceptance.
    blueprint = validate_blueprint_document(document, source=fixture_path.name)

    assert isinstance(blueprint, Blueprint)
    # The ID is checked in both directions so a fixture that is
    # accidentally edited to have a different ID in YAML vs. model
    # reports which direction diverged. In practice, direction is
    # always "model lost it" — but making the assertion bidirectional
    # means the failure message is useful without investigation.
    assert blueprint.id == document["id"]
    assert document["id"] == blueprint.id


# ---------------------------------------------------------------------------
# Property-test seeds
# ---------------------------------------------------------------------------
@pytest.mark.unit()
@pytest.mark.parametrize(
    "fixture_path",
    _property_fixture_paths(),
    ids=lambda p: p.stem,
)
def test_property_seed_parses_into_blueprint_model(fixture_path: Path) -> None:
    """Every Hypothesis seed parses, so the parity test has a valid baseline.

    If a seed stops parsing, the parity test will still run — it will
    just start from a corrupted baseline, and its failures will be
    misattributed to "the model and schema disagree" when the real
    problem is "the seed is no longer a valid document." Running the
    seeds here makes the real problem obvious before the parity test
    even gets a chance to muddy the waters.

    The seeds are *deliberately* broader than the target blueprints
    (each one exercises a specific schema branch, per the README in
    that directory). A seed failing here is a stronger signal than a
    target failing: the seeds are curated to hit edge cases, so a
    regression on an edge case is caught here rather than by a user.
    """
    document = _load_document(fixture_path)

    blueprint = validate_blueprint_document(document, source=fixture_path.name)

    assert isinstance(blueprint, Blueprint)
    assert blueprint.id == document["id"]


# ---------------------------------------------------------------------------
# Structural assertions on a representative parsed model
# ---------------------------------------------------------------------------
@pytest.mark.unit()
def test_parsed_model_exposes_typed_fields() -> None:
    """Parsed fields are typed, not just present.

    The parameterised tests above prove parsing succeeds and preserves
    the ID. This test proves the *type* of two representative fields is
    what downstream code will assume:

    * ``category`` must be a ``Category`` enum, not the raw string.
      Every caller that switches on category (the wizard's grouping,
      the future ``forge list --category``) assumes enum identity, so a
      regression that left it as a string would break those callers at
      the point of comparison rather than at the point of parsing —
      harder to diagnose.

    * ``verification`` must be a non-empty list of ``CheckDefinition``
      instances. The empty case is impossible by schema
      (``min_length=1``), so asserting non-emptiness also asserts the
      model *enforces* the schema — a subtle way of keeping the model
      honest without duplicating the schema's own tests.

    A fixture is used rather than a hand-built document to keep the
    test aligned with real inputs. Picking ``01-minimal`` (the smallest
    valid blueprint) makes the two assertions easy to inspect by hand.
    """
    fixture = _PROPERTY_DIR / "01-minimal.yaml"
    document = _load_document(fixture)

    blueprint = validate_blueprint_document(document, source=fixture.name)

    # ``Category`` is a ``str, Enum`` — comparing to the enum member is
    # what a consumer will do, so the assertion reflects real usage
    # rather than just checking ``isinstance``.
    assert blueprint.category is Category.other
    # Belt-and-braces: ``isinstance`` catches the case where a future
    # refactor returns a plain string that happens to compare equal
    # (``"other" == Category.other`` is ``True`` because ``Category``
    # subclasses ``str``). Only an identity-or-type check catches that.
    assert isinstance(blueprint.category, Category)

    assert len(blueprint.verification) >= 1
    # Every element is a typed ``CheckDefinition``, not a dict that
    # happens to have ``id`` and ``type`` keys. Downstream verification
    # code calls ``check.command`` and ``check.timeout``; if the list
    # contained dicts, those attribute accesses would raise at
    # verification time rather than parsing time.
    for check in blueprint.verification:
        assert isinstance(check, object)
        assert hasattr(check, "id")
        assert hasattr(check, "type")


@pytest.mark.unit()
def test_metadata_view_mirrors_root_fields() -> None:
    """``Blueprint.metadata()`` returns a view whose fields match the root.

    ``BlueprintMetadata`` is an ergonomic view (``test_model_error_messages``
    covers its use as an error-context carrier). It is *not* a
    duplicated source of state — the view is derived on each call from
    the root model's fields. This test proves that derivation is
    faithful: a regression that hard-coded a field in the view, or
    that forgot to copy one, would break ``forge list`` output without
    breaking any other test.

    The check is field-by-field rather than ``==`` because
    ``BlueprintMetadata`` is a separate type from ``Blueprint``; equality
    would require a custom ``__eq__`` and would not tell the reader
    which field diverged when the test fails.
    """
    fixture = _PROPERTY_DIR / "06-multiple-variable-types.yaml"
    document = _load_document(fixture)

    blueprint = validate_blueprint_document(document, source=fixture.name)
    metadata = blueprint.metadata()

    assert metadata.id == blueprint.id
    assert metadata.name == blueprint.name
    assert metadata.version == blueprint.version
    assert metadata.description == blueprint.description
    assert metadata.category == blueprint.category
    assert metadata.maintainer == blueprint.maintainer


@pytest.mark.unit()
def test_parsed_model_is_immutable() -> None:
    """Parsed blueprints are frozen, so they cannot be mutated after the fact.

    ``_StrictModel`` sets ``frozen=True`` in ``model_config``. That is
    not cosmetic: blueprints are read-only descriptors once loaded, and
    the generation pipeline is free to pass the same instance to
    multiple workers. A mutation bug in one worker would be invisible
    until a later worker saw the corruption — the worst possible
    debugging scenario, because the failing code and the buggy code
    are in different threads.

    The test asserts ``FrozenInstanceError`` specifically (Pydantic's
    documented exception for attempted assignment), not a bare
    ``Exception``. Asserting the specific exception keeps the test
    meaningful if a future refactor accidentally loosens ``frozen=True``
    and something else happens to raise — a bare ``Exception`` would
    hide that regression.
    """
    from pydantic import ValidationError

    fixture = _PROPERTY_DIR / "01-minimal.yaml"
    document = _load_document(fixture)
    blueprint = validate_blueprint_document(document, source=fixture.name)

    # Pydantic v2 raises ``ValidationError`` from assignment to a frozen
    # model (not ``FrozenInstanceError``, which is a v1 concept and is
    # only raised by direct ``object.__setattr__`` misuse). The
    # ``ValidationError`` message contains "frozen" — asserting on the
    # message is brittle across Pydantic minor versions, so we assert
    # only the type, which is stable.
    with pytest.raises(ValidationError):
        blueprint.name = "mutated"  # type: ignore[misc]


@pytest.mark.unit()
@pytest.mark.parametrize(
    "model_name",
    [
        "Blueprint",
        "BlueprintMetadata",
        "Compatibility",
        "VariableValidation",
        "FileEntry",
        "ConditionalFileEntry",
        "VariableDefinition",
        "CheckDefinition",
    ],
)
def test_every_model_is_frozen(model_name: str) -> None:
    """Every model in the tree must be frozen, not just the root.

    The previous version of this test only checked ``Blueprint``, which is
    why the loss of ``frozen=True`` on the nested models went unnoticed.
    ``frozen`` is a tree-wide invariant: a mutable ``VariableDefinition``
    inside an otherwise-frozen ``Blueprint`` is a data race waiting to
    happen the moment the generation pipeline shares one parsed blueprint
    across workers.

    The test asserts the *class-level* config, not an instance-level
    behaviour, because:
    * The config is what determines behaviour, and it is what regressed.
    * Checking instances requires constructing a valid instance for every
      model, which means a valid document for every model — more fragile
      and harder to read.
    * Pydantic merges class config from bases, so a child that does not
      declare ``frozen=True`` but inherits it from a base will still be
      frozen; the class-level check is exactly the right granularity.

    The model list is deliberately explicit rather than derived from
    ``__all__`` — a new model that is not in this list will not be
    caught by this test, but it *will* be caught by the reviewer adding
    it to the tree (this file has one test per invariant; that is the
    point of a test file).
    """
    from forge import models

    model_cls = getattr(models, model_name)
    # ``model_config`` is a class attribute; on Pydantic models it is a
    # dict-like object. ``.get`` is the safe accessor — a model that has
    # no config returns ``None``, which is not ``True`` and fails the
    # assertion with a message naming the model, which is the useful
    # diagnostic.
    config = getattr(model_cls, "model_config", {})
    assert config.get("frozen") is True, (
        f"{model_name} is not frozen; ``frozen=True`` must be in its "
        f"``model_config``. Current config: {dict(config)}"
    )

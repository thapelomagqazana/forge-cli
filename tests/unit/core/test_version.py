"""Unit tests for ``forge.core.version.get_version``.

The version resolver has four sources (in order):

1. Installed package metadata (``importlib.metadata.version``).
2. The bundled ``forge._version`` module, generated by ``hatch-vcs``.
3. The ``FORGE_VERSION`` environment variable.
4. The ``"0.0.0.dev0"`` fallback.

Every source is exercised below by mocking the one above it. No test
requires reinstalling the package, uninstalling it, or spawning a
subprocess. The suite runs in a few milliseconds.

Test organisation
-----------------
- ``TestHappyPath``: metadata is available, the version is returned.
- ``TestFallbackChain``: each fallback source in isolation.
- ``TestPrecedence``: the order of sources is enforced.
- ``TestCaching``: the version is read once per process.
- ``TestPublicAPI``: ``forge.__version__`` and ``__all__``.
- ``TestCLIIntegration``: ``forge --version`` uses the resolver.
- ``TestPEP440``: the fallback string is a valid version.
"""

from __future__ import annotations

import sys
from importlib.metadata import PackageNotFoundError
from unittest.mock import patch

import pytest
from packaging.version import InvalidVersion, Version

from forge.core.version import (
    FALLBACK_VERSION,
    PACKAGE_NAME,
    get_version,
)


# -----------------------------------------------------------------------------
# Shared fixtures
# -----------------------------------------------------------------------------
@pytest.fixture(autouse=True)
def _clear_version_cache() -> None:
    """Clear the ``get_version`` cache before and after every test.

    ``get_version`` is decorated with ``@lru_cache(maxsize=1)``, so a
    result cached in one test would leak into the next. Clearing before
    *and* after means:

    - Before: each test starts from a clean slate.
    - After: a test that polluted the cache (e.g., by returning a fake
      version) does not poison the next test.
    """
    get_version.cache_clear()
    yield
    get_version.cache_clear()


class _FakeBundledVersion:
    """A stand-in for the generated ``forge._version`` module.

    ``sys.modules`` entries must be module-like objects. ``get_version``
    only reads ``__version__`` from the module, so an object with that
    attribute is sufficient. Using a real class (rather than a
    ``SimpleNamespace``) makes the intent explicit in the test.
    """

    def __init__(self, version_string: str) -> None:
        self.__version__ = version_string


# -----------------------------------------------------------------------------
# Happy path
# -----------------------------------------------------------------------------
class TestHappyPath:
    """The normal path: metadata is available."""

    @pytest.mark.unit()
    def test_returns_installed_metadata_version(self) -> None:
        """``get_version()`` returns the version from ``importlib.metadata``.

        This is the primary contract: the resolver must return exactly
        what ``importlib.metadata.version("forge-cli")`` returns. If it
        did not, ``forge --version`` would disagree with ``pip show
        forge-cli`` — the exact drift the ADR set out to prevent.
        """
        from importlib.metadata import version as real_version

        expected = real_version(PACKAGE_NAME)
        assert get_version() == expected

    @pytest.mark.unit()
    def test_returns_a_string(self) -> None:
        """The return type is ``str``, never ``None`` or a tuple."""
        result = get_version()
        assert isinstance(result, str)
        assert result != ""

    @pytest.mark.unit()
    def test_never_raises(self) -> None:
        """The happy path never raises, even if metadata is malformed.

        ``importlib.metadata.version`` can raise ``PackageNotFoundError``
        only. We do not catch other exceptions in the happy path, so this
        test is a guard against accidental broad ``except`` clauses
        swallowing real errors.
        """
        assert get_version()  # truthy, no exception


# -----------------------------------------------------------------------------
# Fallback chain — each source in isolation
# -----------------------------------------------------------------------------
class TestFallbackChain:
    """Each fallback source, exercised in isolation."""

    @pytest.mark.unit()
    def test_falls_back_to_bundled_version_when_metadata_missing(self) -> None:
        """Source 2: if metadata is missing, ``_version.py`` is used.

        This is the path used by frozen binaries (PyInstaller, Nuitka,
        cx_Freeze), which strip ``importlib.metadata`` but can still
        import a bundled ``_version.py``.
        """
        with (
            patch(
                "forge.core.version.version",
                side_effect=PackageNotFoundError(PACKAGE_NAME),
            ),
            patch.dict(sys.modules, {"forge._version": _FakeBundledVersion("1.2.3")}),
        ):
            assert get_version() == "1.2.3"

    @pytest.mark.unit()
    def test_falls_back_to_env_var_when_metadata_and_bundled_missing(self) -> None:
        """Source 3: if metadata and ``_version.py`` are missing, env var wins.

        ``FORGE_VERSION`` is a testing/CI escape hatch. It exists so a
        container can simulate a version without reinstalling the
        package.
        """
        with (
            patch(
                "forge.core.version.version",
                side_effect=PackageNotFoundError(PACKAGE_NAME),
            ),
            patch.dict(sys.modules, {"forge._version": None}),
            patch.dict("os.environ", {"FORGE_VERSION": "9.9.9"}),
        ):
            assert get_version() == "9.9.9"

    @pytest.mark.unit()
    def test_falls_back_to_dev0_when_everything_missing(self) -> None:
        """Source 4: if every source is unavailable, the fallback is returned.

        ``"0.0.0.dev0"`` is chosen over ``"unknown"`` because it is a
        valid PEP 440 version. Downstream parsers
        (``packaging.version.Version``) do not crash on it.
        """
        with (
            patch(
                "forge.core.version.version",
                side_effect=PackageNotFoundError(PACKAGE_NAME),
            ),
            patch.dict(sys.modules, {"forge._version": None}),
            patch.dict("os.environ", {}, clear=True),
        ):
            assert get_version() == FALLBACK_VERSION
            assert FALLBACK_VERSION == "0.0.0.dev0"

    @pytest.mark.unit()
    def test_ignores_empty_env_var(self) -> None:
        """An empty ``FORGE_VERSION`` is treated as "not set".

        ``.strip()`` in the resolver means ``FORGE_VERSION=" "`` is also
        ignored. This prevents an accidental empty env var from
        overriding the dev fallback.
        """
        with (
            patch(
                "forge.core.version.version",
                side_effect=PackageNotFoundError(PACKAGE_NAME),
            ),
            patch.dict(sys.modules, {"forge._version": None}),
            patch.dict("os.environ", {"FORGE_VERSION": "   "}),
        ):
            assert get_version() == FALLBACK_VERSION

    @pytest.mark.unit()
    def test_bundled_version_can_be_any_pep440_string(self) -> None:
        """Source 2 accepts any non-empty string, not just semver.

        ``hatch-vcs`` can produce strings like ``0.1.dev4+g7ea9a48e3``,
        which are valid PEP 440 but not semver. The resolver must not
        reject them.
        """
        with (
            patch(
                "forge.core.version.version",
                side_effect=PackageNotFoundError(PACKAGE_NAME),
            ),
            patch.dict(
                sys.modules,
                {"forge._version": _FakeBundledVersion("0.1.dev4+g7ea9a48e3")},
            ),
        ):
            assert get_version() == "0.1.dev4+g7ea9a48e3"


# -----------------------------------------------------------------------------
# Precedence — sources are tried in order
# -----------------------------------------------------------------------------
class TestPrecedence:
    """The order of sources is enforced, not just "one of them wins"."""

    @pytest.mark.unit()
    def test_metadata_wins_over_bundled(self) -> None:
        """If metadata is available, ``_version.py`` is not consulted."""
        from importlib.metadata import version as real_version

        real = real_version(PACKAGE_NAME)
        with patch.dict(sys.modules, {"forge._version": _FakeBundledVersion("9.9.9")}):
            assert get_version() == real

    @pytest.mark.unit()
    def test_metadata_wins_over_env_var(self) -> None:
        """If metadata is available, ``FORGE_VERSION`` is not consulted.

        This is the single most important precedence test. A CI job that
        sets ``FORGE_VERSION`` must not accidentally override the real
        installed version — that would make tests pass against a version
        that does not match the code under test.
        """
        from importlib.metadata import version as real_version

        real = real_version(PACKAGE_NAME)
        with patch.dict("os.environ", {"FORGE_VERSION": "9.9.9"}):
            assert get_version() == real

    @pytest.mark.unit()
    def test_bundled_wins_over_env_var(self) -> None:
        """If ``_version.py`` is available, ``FORGE_VERSION`` is not consulted."""
        with (
            patch(
                "forge.core.version.version",
                side_effect=PackageNotFoundError(PACKAGE_NAME),
            ),
            patch.dict(sys.modules, {"forge._version": _FakeBundledVersion("1.2.3")}),
            patch.dict("os.environ", {"FORGE_VERSION": "9.9.9"}),
        ):
            assert get_version() == "1.2.3"


# -----------------------------------------------------------------------------
# Caching
# -----------------------------------------------------------------------------
class TestCaching:
    """The version is read once per process, not once per call."""

    @pytest.mark.unit()
    def test_cached_after_first_call(self) -> None:
        """Three calls to ``get_version()`` invoke the reader exactly once.

        This is a correctness invariant, not an optimisation. A CLI
        that reports different versions on the same invocation is a bug.
        ``@lru_cache(maxsize=1)`` makes the version immutable for the
        lifetime of the process.
        """
        from importlib.metadata import version as real_version

        with patch("forge.core.version.version", wraps=real_version) as spy:
            get_version()
            get_version()
            get_version()
            assert spy.call_count == 1

    @pytest.mark.unit()
    def test_cache_can_be_cleared(self) -> None:
        """``get_version.cache_clear()`` allows a fresh read.

        Used by tests that need to simulate a version change, and by
        development tools that reload the package in-process.
        """
        from importlib.metadata import version as real_version

        get_version()
        with patch("forge.core.version.version", wraps=real_version) as spy:
            get_version.cache_clear()
            get_version()
            assert spy.call_count == 1

    @pytest.mark.unit()
    def test_cache_survives_environment_changes(self) -> None:
        """Changing ``FORGE_VERSION`` after the first call has no effect.

        This is intentional. The cache means "the version does not
        change during the process." A user who sets ``FORGE_VERSION``
        *after* Forge has already resolved its version is not asking
        for a re-read — they are setting a variable Forge has already
        finished with.
        """
        from importlib.metadata import version as real_version

        # Prime the cache with the real version.
        real = real_version(PACKAGE_NAME)
        assert get_version() == real

        # Changing the env var does not change the cached answer.
        with patch.dict("os.environ", {"FORGE_VERSION": "9.9.9"}):
            assert get_version() == real


# -----------------------------------------------------------------------------
# Public API
# -----------------------------------------------------------------------------
class TestPublicAPI:
    """``forge.__version__`` and ``__all__`` are part of the public API."""

    @pytest.mark.unit()
    def test_forge_dunder_version_matches_get_version(self) -> None:
        """``forge.__version__`` equals ``get_version()``.

        The library API and the callable API must agree. If they do
        not, external tools cannot trust either.
        """
        import forge

        assert forge.__version__ == get_version()

    @pytest.mark.unit()
    def test_forge_dunder_version_is_a_string(self) -> None:
        """``forge.__version__`` is a ``str``, not a tuple or None."""
        import forge

        assert isinstance(forge.__version__, str)
        assert forge.__version__ != ""

    @pytest.mark.unit()
    def test_get_version_is_exported(self) -> None:
        """``get_version`` is listed in ``forge.core.version.__all__``."""
        from forge.core import version as version_module

        assert "get_version" in version_module.__all__
        assert "FALLBACK_VERSION" in version_module.__all__
        assert "PACKAGE_NAME" in version_module.__all__

    @pytest.mark.unit()
    def test_package_name_is_pypi_distribution_name(self) -> None:
        """``PACKAGE_NAME`` is the PyPI distribution name, not the import name.

        ``importlib.metadata.version`` takes the *distribution* name
        (``forge-cli``), not the *import* name (``forge``). Getting this
        wrong is a common source of ``PackageNotFoundError`` in tests
        that pass on one machine and fail on another.
        """
        assert PACKAGE_NAME == "forge-cli"
        assert PACKAGE_NAME != "forge"


# -----------------------------------------------------------------------------
# CLI integration
# -----------------------------------------------------------------------------
class TestCLIIntegration:
    """``forge --version`` uses the resolver, not a hard-coded string."""

    @pytest.mark.unit()
    def test_version_callback_prints_resolved_version(self) -> None:
        """``forge --version`` prints ``forge, version <resolved>``."""
        from typer.testing import CliRunner

        from forge.cli.main import create_app

        runner = CliRunner()
        result = runner.invoke(create_app(), ["--version"])

        assert result.exit_code == 0
        assert "forge, version" in result.stdout
        assert get_version() in result.stdout

    @pytest.mark.unit()
    def test_version_callback_uses_get_version(self) -> None:
        """The callback calls ``get_version()``, not a private resolver.

        If someone reintroduces an inline resolver in ``main.py``, this
        test fails — which is the signal to move the logic back to
        ``forge.core.version``.
        """
        from unittest.mock import patch

        from typer.testing import CliRunner

        from forge.cli.main import create_app

        with patch("forge.cli.main.get_version", return_value="9.9.9") as spy:
            runner = CliRunner()
            result = runner.invoke(create_app(), ["--version"])

            assert result.exit_code == 0
            assert "9.9.9" in result.stdout
            spy.assert_called_once()


# -----------------------------------------------------------------------------
# PEP 440 validity
# -----------------------------------------------------------------------------
class TestPEP440:
    """Every value returned by ``get_version`` is a valid PEP 440 version."""

    @pytest.mark.unit()
    def test_fallback_is_pep440_valid(self) -> None:
        """``"0.0.0.dev0"`` parses with ``packaging.version.Version``.

        Downstream code that compares versions (e.g., checking whether
        the installed Forge satisfies a blueprint's
        ``min_forge_version``) will do
        ``Version(get_version()) >= Version(...)``. If the fallback
        were ``"unknown"``, that comparison would raise
        ``InvalidVersion``.
        """
        Version(FALLBACK_VERSION)  # raises if invalid

    @pytest.mark.unit()
    def test_real_version_is_pep440_valid(self) -> None:
        """The resolved version (from metadata) is PEP 440 valid."""
        Version(get_version())  # raises if invalid

    @pytest.mark.unit()
    def test_dev0_is_less_than_any_release(self) -> None:
        """``"0.0.0.dev0"`` compares less than ``"0.0.1"``.

        This is the property that makes the fallback safe: a project
        requiring ``forge >= 0.1.0`` will correctly reject the fallback,
        so a development checkout cannot silently masquerade as a
        supported release.
        """
        assert Version(FALLBACK_VERSION) < Version("0.0.1")

    @pytest.mark.unit()
    def test_invalid_version_string_raises(self) -> None:
        """``packaging.version.Version`` rejects ``"unknown"``.

        This is why ``"unknown"`` is *not* the fallback. The test is a
        guard against a future contributor "simplifying" the fallback
        to a non-PEP-440 string.
        """
        with pytest.raises(InvalidVersion):
            Version("unknown")

"""Dynamic version resolution for Forge CLI.

The version of Forge is *not* a string embedded in the source code. It is
read from the installed package metadata, so that ``forge --version``
always reports the version that was actually installed — no drift, no
forgotten bumps, no "works on my machine".

Resolution order
----------------
The resolver tries three sources, in order, and returns the first one
that succeeds:

1. **Installed package metadata** (``importlib.metadata``). This is the
   normal path: ``uv tool install forge-cli``, ``pip install forge-cli``,
   and ``uv sync`` all populate the metadata. Reading from it is fast
   and always accurate.

2. **Bundled ``_version.py``**. ``hatch-vcs`` generates this file at
   build time from the Git tag. It exists so that frozen binaries
   (PyInstaller, Nuitka, cx_Freeze) — which strip ``importlib.metadata``
   — can still report a version. The file is in ``.gitignore`` and is
   never committed.

3. **Honest fallback** (``"0.0.0.dev0"``). When neither of the above is
   available (e.g., a bare source checkout that was never installed),
   we return a version string that is clearly a development placeholder.
   This turns "forge --version crashes" into "forge --version tells the
   truth: I am a dev checkout".

Caching
-------
The result is cached with ``@lru_cache(maxsize=1)``. This is not a
performance optimisation — it is a correctness invariant. A CLI that
reports different versions on the same invocation is a bug. Caching the
result makes the version immutable for the lifetime of the process.

Environment override
--------------------
``FORGE_VERSION`` overrides the *fallback only*, never the installed
metadata. It exists so CI can simulate a specific version when the real
version is unavailable (e.g., testing migration paths in a container
that has no installed package). The override is intentionally last in
precedence: the real installed version should always win.
"""

from __future__ import annotations

import os
from functools import lru_cache
from importlib.metadata import PackageNotFoundError, version

# -----------------------------------------------------------------------------
# Constants
# -----------------------------------------------------------------------------
PACKAGE_NAME = "forge-cli"
"""The PyPI distribution name. Distinct from the import name (``forge``)."""

FALLBACK_VERSION = "0.0.0.dev0"
"""Returned when no version can be resolved from metadata or ``_version.py``.

Chosen over ``"unknown"`` because ``"0.0.0.dev0"`` is a *valid* PEP 440
version string, so downstream code that parses it with ``packaging.version``
will not crash. It is also clearly a development placeholder, so users
will not mistake it for a real release.
"""


# -----------------------------------------------------------------------------
# Resolver
# -----------------------------------------------------------------------------
@lru_cache(maxsize=1)
def get_version() -> str:
    """Return the Forge version, resolved from the best available source.

    Resolution order (first success wins):

    1. Installed package metadata via ``importlib.metadata``.
    2. Bundled ``_version.py`` (generated by ``hatch-vcs`` at build time).
    3. ``FORGE_VERSION`` environment variable.
    4. ``FALLBACK_VERSION`` (``"0.0.0.dev0"``).

    The result is cached for the lifetime of the process. Call
    ``get_version.cache_clear()`` to force a re-read (used only in tests).

    Returns:
        A PEP 440 version string. Never raises.
    """
    # -------------------------------------------------------------------------
    # Source 1: installed package metadata
    # -------------------------------------------------------------------------
    try:
        return version(PACKAGE_NAME)
    except PackageNotFoundError:
        # Running from a source checkout that was never installed.
        # Fall through to the bundled fallback.
        pass

    # -------------------------------------------------------------------------
    # Source 2: bundled _version.py (generated by hatch-vcs)
    # -------------------------------------------------------------------------
    # The file is generated at build time and is present in installed
    # wheels. It is absent in a bare source checkout. We import it lazily
    # so a missing file raises ImportError, which we catch.
    try:
        from forge._version import __version__ as bundled_version

        if bundled_version:
            return str(bundled_version)
    except ImportError:
        # No bundled _version.py — we are in a source checkout.
        pass

    # -------------------------------------------------------------------------
    # Source 3: FORGE_VERSION environment variable
    # -------------------------------------------------------------------------
    # A testing and CI escape hatch. Never overrides real metadata — by the
    # time we reach here, the real metadata is unavailable.
    env_version = os.environ.get("FORGE_VERSION", "").strip()
    if env_version:
        return env_version

    # -------------------------------------------------------------------------
    # Source 4: honest fallback
    # -------------------------------------------------------------------------
    return FALLBACK_VERSION


# -----------------------------------------------------------------------------
# Public re-exports
# -----------------------------------------------------------------------------
__all__ = ["FALLBACK_VERSION", "PACKAGE_NAME", "get_version"]
